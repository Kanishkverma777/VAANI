@pytest.mark.asyncio
async def test_generate_agent_success(async_client: AsyncClient):
    """Test successful agent configuration generation from natural language prompt."""
    payload = {
        "description": "Create a friendly voice agent for a dental clinic that books checkup appointments.",
        "use_case": "appointments",
        "preferred_language": "en",
    }

    with patch(
        "app.integrations.llm_client.LLMClient.generate_structured_json",
        new_callable=AsyncMock,
        return_value=SAMPLE_VALID_GENERATED_CONFIG,
    ):
        response = await async_client.post("/api/v1/agents/generate", json=payload)
        assert response.status_code == 200
        data = response.json()
        assert "configuration" in data
        config = data["configuration"]
        assert config["name"] == "Dental Assistant AI"
        assert config["use_case"] == UseCaseEnum.APPOINTMENTS.value
        assert "welcome_message" in config
        assert config["guardrails"]["max_turn_count"] == 25


