@pytest.mark.asyncio
async def test_generate_agent_prompt_length_limit(async_client: AsyncClient):
    """Test that prompts exceeding the max character limit are rejected with 422."""
    payload = {
        "description": "a" * 5001,
        "use_case": "customer_support",
    }
    response = await async_client.post("/api/v1/agents/generate", json=payload)
    assert response.status_code == 422
    data = response.json()
    assert data["error"]["code"] == "VALIDATION_ERROR"


@pytest.mark.asyncio
async def test_generate_agent_malformed_llm_output(async_client: AsyncClient):
    """Test handling of invalid schema generated by LLM."""
    malformed = {"name": "Incomplete Agent"}  # Missing required fields like instructions, etc.

    with patch(
        "app.integrations.llm_client.LLMClient.generate_structured_json",
        new_callable=AsyncMock,
        return_value=malformed,
    ):
        response = await async_client.post(
            "/api/v1/agents/generate",
            json={"description": "Voice bot for bookings", "use_case": "appointments"},
        )
        assert response.status_code == 422
        data = response.json()
        assert data["error"]["code"] == "INVALID_GENERATED_SCHEMA"


@pytest.mark.asyncio
async def test_generate_agent_provider_rate_limit(async_client: AsyncClient):
    """Test handling when LLM provider rate limit is exceeded."""
    with patch(
        "app.integrations.llm_client.LLMClient.generate_structured_json",
        new_callable=AsyncMock,
        side_effect=RateLimitException("Rate limit reached"),
    ):
        response = await async_client.post(
            "/api/v1/agents/generate",
            json={"description": "Voice bot for bookings", "use_case": "appointments"},
        )
        assert response.status_code == 429
        data = response.json()
        assert data["error"]["code"] == "RATE_LIMIT_EXCEEDED"
