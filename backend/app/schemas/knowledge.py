from typing import List, Optional

from pydantic import BaseModel, Field


class KnowledgeSourceResponse(BaseModel):
    id: str
    agent_id: str
    owner_id: str
    filename: str
    content_type: str
    storage_reference: str
    processing_status: str
    chunk_count: int
    error_message: Optional[str] = None
    created_at: str
    updated_at: str


class KnowledgeQueryRequest(BaseModel):
    query: str = Field(..., min_length=2, max_length=1000, description="Question or search query.")
    top_k: int = Field(default=1, ge=1, le=10)
    confidence_threshold: float = Field(default=0.25, ge=0.0, le=1.0)


class KnowledgeChunkResult(BaseModel):
    chunk_id: str
    score: float
    text: str
    filename: str
    source_id: str


class KnowledgeQueryResponse(BaseModel):
    agent_id: str
    query: str
    answer: Optional[str] = Field(
        default=None,
        description="Synthesized concise answer generated by Groq LLM grounded strictly in retrieved vector chunks.",
    )
    results: List[KnowledgeChunkResult]
    total_matches: int
